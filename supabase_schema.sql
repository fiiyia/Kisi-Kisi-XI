-- 1. Buat tabel utama untuk menyimpan seluruh data isian dan skor murid
CREATE TABLE IF NOT EXISTS public.hasil_latihan_uas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT NOT NULL UNIQUE,
  nama_lengkap TEXT NOT NULL,
  kelas TEXT NOT NULL CHECK (kelas IN ('XI-1', 'XI-2')),
  mode_latihan TEXT NOT NULL CHECK (mode_latihan IN ('belajar', 'simulasi')),

  -- Rincian Skor per Bagian & Total (0 - 100)
  skor_bagian_1 INTEGER NOT NULL DEFAULT 0,
  skor_bagian_2 INTEGER NOT NULL DEFAULT 0,
  skor_bagian_3 INTEGER NOT NULL DEFAULT 0,
  total_skor INTEGER NOT NULL DEFAULT 0,

  -- Rincian Skor per Topik Materi (Polinomial: maks 22, Matriks: maks 59, Translasi: maks 19)
  skor_polinomial INTEGER NOT NULL DEFAULT 0,
  skor_matriks INTEGER NOT NULL DEFAULT 0,
  skor_translasi INTEGER NOT NULL DEFAULT 0,

  -- Seluruh Data Isian Murid (Format JSONB)
  jawaban_bagian_1 JSONB NOT NULL DEFAULT '{}'::jsonb,
  jawaban_bagian_2 JSONB NOT NULL DEFAULT '{}'::jsonb,
  jawaban_bagian_3_teks JSONB NOT NULL DEFAULT '{}'::jsonb,
  jawaban_bagian_3_rubrik JSONB NOT NULL DEFAULT '{}'::jsonb,

  -- Pencatatan Waktu
  waktu_mulai TIMESTAMPTZ,
  waktu_selesai TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Buat indeks untuk mempercepat filter berdasarkan kelas dan waktu pengumpulan
CREATE INDEX IF NOT EXISTS idx_hasil_latihan_uas_kelas ON public.hasil_latihan_uas (kelas);
CREATE INDEX IF NOT EXISTS idx_hasil_latihan_uas_created_at ON public.hasil_latihan_uas (created_at DESC);

-- 3. Trigger otomatis untuk memperbarui kolom updated_at saat murid memperbarui centang rubrik mandiri
CREATE OR REPLACE FUNCTION public.set_updated_at_hasil_latihan_uas()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_hasil_latihan_uas_updated_at ON public.hasil_latihan_uas;
CREATE TRIGGER trg_hasil_latihan_uas_updated_at
BEFORE UPDATE ON public.hasil_latihan_uas
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at_hasil_latihan_uas();

-- 4. Aktifkan Row Level Security (RLS) dan izinkan akses anon key untuk menyimpan & memperbarui jawaban
ALTER TABLE public.hasil_latihan_uas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Izinkan murid menyimpan hasil latihan (INSERT)" ON public.hasil_latihan_uas;
CREATE POLICY "Izinkan murid menyimpan hasil latihan (INSERT)"
  ON public.hasil_latihan_uas
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Izinkan murid memperbarui rubrik mandiri (UPDATE)" ON public.hasil_latihan_uas;
CREATE POLICY "Izinkan murid memperbarui rubrik mandiri (UPDATE)"
  ON public.hasil_latihan_uas
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Izinkan pembacaan data hasil latihan (SELECT)" ON public.hasil_latihan_uas;
CREATE POLICY "Izinkan pembacaan data hasil latihan (SELECT)"
  ON public.hasil_latihan_uas
  FOR SELECT
  TO anon, authenticated
  USING (true);
